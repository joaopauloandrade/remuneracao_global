-- Esquema inicial do Sistema de Remuneração Global (SPEC §3).
-- SQL portável entre PostgreSQL e H2 (modo PostgreSQL).

CREATE TABLE empresa (
    codigo          VARCHAR(20)  PRIMARY KEY,
    sigla           VARCHAR(50)  NOT NULL,
    setor           VARCHAR(100),
    porte           VARCHAR(50),
    controle        VARCHAR(50),
    controladora    BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE instancia_gestao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)  NOT NULL UNIQUE,
    nome                VARCHAR(150) NOT NULL,
    descricao           VARCHAR(500),
    ativo               BOOLEAN      NOT NULL DEFAULT TRUE,
    data_desativacao    TIMESTAMP,
    motivo_desativacao  VARCHAR(500)
);

CREATE TABLE cargo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)  NOT NULL UNIQUE,
    nome                VARCHAR(100) NOT NULL UNIQUE,
    ativo               BOOLEAN      NOT NULL DEFAULT TRUE,
    data_desativacao    TIMESTAMP,
    motivo_desativacao  VARCHAR(500)
);

CREATE TABLE caso (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero           VARCHAR(20) UNIQUE,
    tipo             VARCHAR(10)  NOT NULL,
    empresa_codigo   VARCHAR(20)  NOT NULL REFERENCES empresa(codigo),
    exercicio        INTEGER      NOT NULL,
    tipo_assembleia  VARCHAR(10)  NOT NULL,
    data_assembleia  DATE,
    estado           VARCHAR(30)  NOT NULL,
    justificativa    VARCHAR(4000),
    responsavel      VARCHAR(100),
    criado_por       VARCHAR(100) NOT NULL,
    criado_em        TIMESTAMP    NOT NULL,
    atualizado_em    TIMESTAMP    NOT NULL
);
CREATE INDEX ix_caso_exercicio_estado ON caso (exercicio, estado);
CREATE INDEX ix_caso_responsavel ON caso (responsavel);

CREATE TABLE linha_proposta (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_id             BIGINT       NOT NULL REFERENCES caso(id),
    instancia_id        BIGINT       NOT NULL REFERENCES instancia_gestao(id),
    cargo_id            BIGINT       NOT NULL REFERENCES cargo(id),
    quantidade_membros  INTEGER      NOT NULL,
    honorario_vigente   NUMERIC(18,2) NOT NULL,
    honorario_proposto  NUMERIC(18,2) NOT NULL,
    beneficio_vigente   NUMERIC(18,2) NOT NULL,
    beneficio_proposto  NUMERIC(18,2) NOT NULL,
    total_vigente       NUMERIC(18,2) NOT NULL,
    total_proposto      NUMERIC(18,2) NOT NULL,
    variacao_percentual NUMERIC(10,2) NOT NULL,
    estado              VARCHAR(20)  NOT NULL,
    criado_em           TIMESTAMP    NOT NULL,
    atualizado_em       TIMESTAMP    NOT NULL
);
CREATE INDEX ix_linha_caso ON linha_proposta (caso_id);

-- Snapshot imutável gerado a cada envio de proposta (SPEC §4.2: "Proposta Enviada").
CREATE TABLE proposta_enviada (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_id             BIGINT       NOT NULL REFERENCES caso(id),
    versao              INTEGER      NOT NULL,
    enviado_por         VARCHAR(100) NOT NULL,
    enviado_em          TIMESTAMP    NOT NULL,
    total_vigente       NUMERIC(18,2) NOT NULL,
    total_proposto      NUMERIC(18,2) NOT NULL,
    variacao_percentual NUMERIC(10,2) NOT NULL,
    snapshot            VARCHAR(20000) NOT NULL
);
CREATE INDEX ix_proposta_enviada_caso ON proposta_enviada (caso_id);

-- Histórico oficial de remunerações aprovadas (SPEC §3.2 / §4.3).
CREATE TABLE historico_remuneracao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_codigo      VARCHAR(20)  NOT NULL REFERENCES empresa(codigo),
    exercicio           INTEGER      NOT NULL,
    instancia_id        BIGINT       NOT NULL REFERENCES instancia_gestao(id),
    cargo_id            BIGINT       NOT NULL REFERENCES cargo(id),
    honorario_aprovado  NUMERIC(18,2) NOT NULL,
    beneficio_aprovado  NUMERIC(18,2) NOT NULL,
    quantidade_membros  INTEGER      NOT NULL,
    numero_caso         VARCHAR(20)  NOT NULL,
    portaria            VARCHAR(100),
    data_dou            DATE,
    registrado_em       TIMESTAMP    NOT NULL
);
CREATE INDEX ix_historico_chave ON historico_remuneracao (empresa_codigo, instancia_id, cargo_id, exercicio);

-- Trilha de auditoria append-only (SPEC §7.3).
CREATE TABLE auditoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario        VARCHAR(100) NOT NULL,
    acao           VARCHAR(50)  NOT NULL,
    entidade       VARCHAR(50)  NOT NULL,
    entidade_id    VARCHAR(50)  NOT NULL,
    detalhe        VARCHAR(1000),
    registrado_em  TIMESTAMP    NOT NULL
);
